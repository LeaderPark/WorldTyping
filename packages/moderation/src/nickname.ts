// spec: docs/06 §4.2 (닉네임 규칙·NICK_RE 전문), docs/00 §11-D14(2~12자, 30일당 2회 확정 —
// docs/04 §10.2의 2~16자·7일 1회는 폐기됨. 30일 2회 카운터 자체는 D1 users 테이블/API 레벨에서
// 관리하며 이 패키지의 책임 밖이다).
//
// NICK_RE는 docs/06 §4.2 코드 블록과 동일한 판정을 하도록 옮긴 것이다 — 임의 변형 금지.
// 문자 클래스 끝에 오는 `-`는 이스케이프 없이도 리터럴로 해석되므로(범위 연산자가 아님)
// docs 원문의 `[_\-]`를 `[_-]`로 옮겨 적어도 판정은 완전히 동일하다(eslint no-useless-escape).

/**
 * 닉네임 형식 정규식 (docs/06 §4.2 전문):
 * - 길이 2~12자(코드포인트 기준)
 * - 허용 문자: 완성형 한글 · 라틴 알파벳 · 숫자 · `_` · `-`
 * - 최소 1개의 한글 또는 라틴 문자 포함(숫자/기호만 구성 불가)
 * - 선두/말미에 `_`/`-` 불가, `_`/`-` 연속 불가
 */
export const NICK_RE =
  /^(?![_-])(?!.*[_-]{2})(?=.*[가-힣a-zA-Z])[가-힣a-zA-Z0-9_-]{2,12}(?<![_-])$/u;

/**
 * 중복 검사용 정규화 (docs/06 §4.2: NFC → lowercase). leet 치환은 과잉 차단을 막기 위해
 * 여기서는 적용하지 않는다 — 비속어 판정(leet 포함)과 유일성 정규화는 서로 다른 목적이다.
 */
export function normalizeNickname(name: string): string {
  return name.normalize('NFC').toLowerCase();
}
